// Exercise the actual generated WASM boundary, including JSON Number effect IDs.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const directory=resolve(process.argv[2]);
const {default:init,ExtensionEngine}=await import(pathToFileURL(`${directory}/computa_extension.js`));
await init({module_or_path:await readFile(`${directory}/computa_extension_bg.wasm`)});
const installation='79e4505e-e068-4c75-87ca-309c060a8c41';
const extension='gdghbmoiibghgkfmhjlckipjjlclnlbk';
const engine=new ExtensionEngine(installation,extension,crypto.randomUUID());
let effects=engine.dispatch({kind:'bootstrap',local:{macndashChromeBridgeV1:{installationId:installation,pairingToken:'a'.repeat(64),suspended:false}},session:{},now:0});
assert(Array.isArray(effects));assert(effects.every(e=>Object.getPrototypeOf(e)===Object.prototype));
assert(effects.some(e=>e.kind==='connect'));
let sequence=0;
const request=(operation,params)=>engine.dispatch({kind:'native',message:{version:1,id:`wasm-${++sequence}`,operation,params,generation:'g'},now:0});
effects=request('authorizeSession',{installationId:installation,pairingToken:'a'.repeat(64),temporaryTabsVersion:1});
assert(effects.some(e=>e.kind==='emit'&&e.message.ok===true));
effects=request('webProviderStart',{provider:'claude'});
let effect=effects.find(e=>e.kind==='chrome');
assert.equal(effect.api,'tabs.create');assert.equal(typeof effect.id,'number');assert.equal(engine.permits(effect.id),true);
assert.equal(engine.permits(-1),false);assert.equal(engine.permits(1.5),false);assert.equal(engine.permits(NaN),false);
effects=engine.dispatch({kind:'chromeReply',id:effect.id,result:{id:42,active:false},error:null,now:0});
assert.equal(engine.permits(effect.id),false);effect=effects.find(e=>e.kind==='chrome');assert.equal(effect.api,'debugger.attach');
effects=engine.dispatch({kind:'chromeReply',id:effect.id,result:{},error:null,now:0});
const result=effects.find(e=>e.kind==='emit'&&e.message.ok)?.message.result;
assert.equal(result.state,'loading');assert.equal(result.provider,'claude');assert.equal(typeof result.sessionToken,'string');
effects=request('webProviderPoll',{sessionToken:result.sessionToken});effect=effects.find(e=>e.kind==='chrome');
effects=engine.dispatch({kind:'chromeReply',id:effect.id,result:{},error:null,now:1});
assert.equal(effects.find(e=>e.kind==='emit'&&e.message.ok)?.message.result.state,'loading');
assert(engine.accepts_popup({id:extension,url:`chrome-extension://${extension}/popup.html`}));
assert(!engine.accepts_popup({id:extension,url:'https://example.test'}));
const reconnect=new ExtensionEngine(installation,extension,crypto.randomUUID());
reconnect.dispatch({kind:'bootstrap',local:{macndashChromeBridgeV1:{installationId:installation,pairingToken:'a'.repeat(64),suspended:false}},session:{},now:0});
let stale;
for(let attempt=0;attempt<20;attempt++) {
  effects=reconnect.dispatch({kind:'hostDisconnected',connection:0,now:attempt*30000});
  const schedules=effects.filter(e=>e.kind==='schedule');
  assert.equal(schedules.length,1);
  const scheduled=schedules[0];
  assert.equal(typeof scheduled.token,'number');
  assert.equal(scheduled.afterMs,Math.min(1000*2**Math.min(attempt,5),30000));
  assert(!effects.some(e=>e.kind==='chrome'));
  if(stale!==undefined) assert.deepEqual(reconnect.dispatch({kind:'timer',token:stale,now:attempt*30000}),[]);
  effects=reconnect.dispatch({kind:'timer',token:scheduled.token,now:attempt*30000+scheduled.afterMs});
  assert.equal(effects.filter(e=>e.kind==='connect').length,1);
  assert(!effects.some(e=>e.kind==='chrome'||e.kind==='schedule'||(e.kind==='emit'&&e.message.id)));
  stale=scheduled.token;
}
console.log('WASM extension boundary: base checks and 20 persistent reconnect cycles passed');
